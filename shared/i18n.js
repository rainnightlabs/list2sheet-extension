export function t(key,lang="en",...args){
  const value=MESSAGES[lang]?.[key] ?? MESSAGES.en[key] ?? key;
  return typeof value==="function" ? value(...args) : value;
}

export async function getUiLanguage(){
  const result=await chrome.storage.local.get(STORAGE_KEY);
  const saved=result[STORAGE_KEY];
  if(saved==="zh"||saved==="en") return saved;
  return String(navigator.language||"").toLowerCase().startsWith("zh") ? "zh" : "en";
}

export async function setUiLanguage(lang){
  const normalized=lang==="zh"?"zh":"en";
  await chrome.storage.local.set({[STORAGE_KEY]:normalized});
  return normalized;
}

export function applyI18n(lang,root=document){
  root.documentElement.lang=lang==="zh"?"zh-CN":"en";
  root.querySelectorAll("[data-i18n]").forEach(element=>{
    element.textContent=t(element.dataset.i18n,lang);
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach(element=>{
    element.placeholder=t(element.dataset.i18nPlaceholder,lang);
  });
}
